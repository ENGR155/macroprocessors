import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(new URL('dashboard.html', import.meta.url), 'utf8').replace(/\r\n/g, '\n').trimEnd();
const target = new URL('esp8266/MaglevWeb/dashboard.h', import.meta.url);
if (html.includes(')MAGLEV"')) throw Error('Dashboard contains the C++ raw string delimiter');
const header = `// Generated by build_dashboard.mjs from dashboard.html.
#pragma once
#include <pgmspace.h>

static const char maglev_dashboard[] PROGMEM = R"MAGLEV(${html})MAGLEV";
`;
if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== header) throw Error('Regenerate the ESP8266 dashboard header');
} else {
    writeFileSync(target, header);
}
